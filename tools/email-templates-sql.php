<?php
/**
 * Prints the factory email templates (get_default_email_templates()) as an INSERT IGNORE block
 * for schema.sql, so fresh installs from the SQL file get the same rows as the PHP seeder.
 * Run after changing a default template and paste the output over the block in schema.sql.
 *
 * Usage: php tools/email-templates-sql.php
 *
 * @package RepuVio
 * @author  Stefan Iftimie <https://www.ahoi.ro/>
 * @company Ahoi Digital SRL
 */

if ( 'cli' !== PHP_SAPI ) {
	http_response_code( 404 );
	exit;
}

define( 'REPUVIO_NO_SESSION', true );

require_once dirname( __DIR__ ) . '/includes/bootstrap.php';

/**
 * SQL string literal (MySQL escaping without a connection-specific quote call).
 *
 * @param string $value Value.
 * @return string
 */
function sql_literal( $value ) {
	return "'" . str_replace( [ '\\', "'", "\n", "\r" ], [ '\\\\', "\\'", '\\n', '\\r' ], (string) $value ) . "'";
}

$values = [];

foreach ( get_default_email_templates() as $slug => $template ) {
	$values[] = "\t(" . implode(
		', ',
		[
			sql_literal( $slug ),
			sql_literal( $template['name'] ),
			sql_literal( $template['category'] ),
			(int) $template['is_enabled'],
			sql_literal( $template['subject'] ),
			sql_literal( $template['body_html'] ),
			sql_literal( $template['subject'] ),
			sql_literal( $template['body_html'] ),
			sql_literal( email_template_json( $template['placeholders'] ) ),
		]
	) . ')';
}

echo "-- System email templates (generated by tools/email-templates-sql.php from includes/email-templates.php).\n";
echo "INSERT IGNORE INTO `email_templates` (`slug`, `name`, `category`, `is_enabled`, `subject`, `body_html`, `default_subject`, `default_body_html`, `available_placeholders`) VALUES\n";
echo implode( ",\n", $values ) . ";\n"; // phpcs:ignore WordPress.Security.EscapeOutput -- CLI SQL output.
