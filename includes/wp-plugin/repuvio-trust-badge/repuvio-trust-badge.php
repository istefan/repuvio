/**
 * Whether the floating badge should load on the current request.
 *
 * @param array $options Options.
 * @return bool
 */
function repuvio_badge_should_float( array $options ) {
	if ( empty( $options['enabled'] ) || '' === $options['url'] || 'shortcode' === $options['position'] || is_admin() ) {
		return false;
	}

	if ( empty( $options['mobile'] ) && wp_is_mobile() ) {
		return false;
	}

	$current_id = (int) get_queried_object_id();

	if ( in_array( $current_id, repuvio_badge_parse_ids( $options['exclude_ids'] ), true ) ) {
		return false;
	}

	if ( 'front_page' === $options['display'] ) {
		return is_front_page();
	}

	if ( 'selected' === $options['display'] ) {
		return in_array( $current_id, repuvio_badge_parse_ids( $options['page_ids'] ), true );
	}

	return true;
}

/**
 * Enqueues the bundled badge script and its configuration.
 *
 * @return void
 */
function repuvio_badge_enqueue() {
	$options = repuvio_badge_options();

	if ( ! repuvio_badge_should_float( $options ) ) {
		return;
	}

	wp_enqueue_script( 'repuvio-badge', plugins_url( 'assets/badge.js', __FILE__ ), array(), REPUVIO_BADGE_VERSION, true );

	$config = array(
		'url'      => $options['url'],
		'name'     => $options['name'],
		'position' => $options['position'],
		'theme'    => $options['theme'],
		'preview'  => false,
	);

	wp_add_inline_script(
		'repuvio-badge',
		'(function(){var c=' . wp_json_encode( $config ) . ';try{if("1"===window.sessionStorage.getItem("rmBadgeClosed")){return;}}catch(e){}'
		. 'function r(){if(window.RepuVioBadge){window.RepuVioBadge.render(document.body,c);}}'
		. 'if("loading"===document.readyState){document.addEventListener("DOMContentLoaded",r);}else{r();}})();'
	);
}
add_action( 'wp_enqueue_scripts', 'repuvio_badge_enqueue' );

/**
 * Inline badge HTML (inline styles, no JavaScript).
 *
 * @param array  $options Options.
 * @param string $theme   light|dark.
 * @return string
 */
function repuvio_badge_inline_html( array $options, $theme ) {
	if ( '' === $options['url'] ) {
		return '';
	}

	$dark   = 'dark' === $theme;
	$bg     = $dark ? '#0F172A' : '#FFFFFF';
	$text   = $dark ? '#FFFFFF' : '#0F172A';
	$muted  = $dark ? '#CBD5E1' : '#64748B';
	$border = $dark ? '#1E293B' : '#E2E8F0';

	return '<a class="repuvio-badge-inline" href="' . esc_url( $options['url'] ) . '" target="_blank" rel="noopener" style="display:inline-flex;align-items:center;gap:10px;padding:10px 16px;border-radius:14px;border:1px solid ' . esc_attr( $border ) . ';background:' . esc_attr( $bg ) . ';color:' . esc_attr( $text ) . ';font-family:Inter,Segoe UI,Arial,sans-serif;text-decoration:none;box-shadow:0 4px 14px rgba(15,23,42,.08);line-height:1.2;">'
		. '<span style="color:#F59E0B;font-size:16px;letter-spacing:1px;">★★★★★</span>'
		. '<span style="display:inline-block;text-align:left;"><strong style="display:block;font-size:14px;">' . esc_html__( 'Evaluează-ne', 'repuvio-trust-badge' ) . '</strong>'
		. '<span style="display:block;font-size:12px;color:' . esc_attr( $muted ) . ';">' . esc_html( $options['name'] ) . '</span></span>'
		. '</a>';
}

/**
 * [repuvio_badge theme="light|dark"] shortcode.
 *
 * @param array $atts Attributes.
 * @return string
 */
function repuvio_badge_shortcode( $atts ) {
	$options = repuvio_badge_options();
	$atts    = shortcode_atts( array( 'theme' => $options['theme'] ), $atts, 'repuvio_badge' );
	$theme   = in_array( $atts['theme'], array( 'light', 'dark' ), true ) ? $atts['theme'] : 'light';

	return repuvio_badge_inline_html( $options, $theme );
}
add_shortcode( 'repuvio_badge', 'repuvio_badge_shortcode' );
