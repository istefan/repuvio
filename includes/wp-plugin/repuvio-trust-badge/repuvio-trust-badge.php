/**
 * Pre-configured values generated by RepuVio for this company (defaults.php is created at download time).
 *
 * @return array
 */
function repuvio_badge_generated_defaults() {
	$file = __DIR__ . '/defaults.php';
	$data = is_readable( $file ) ? include $file : array();

	return is_array( $data ) ? $data : array();
}

/**
 * Brand name of the review platform (set at download time, fallback "RepuVio").
 *
 * @return string
 */
function repuvio_badge_brand() {
	$generated = repuvio_badge_generated_defaults();

	return ! empty( $generated['brand'] ) ? (string) $generated['brand'] : 'RepuVio';
}

/**
 * Default options.
 *
 * @return array
 */
function repuvio_badge_default_options() {
	$generated = repuvio_badge_generated_defaults();

	return array(
		'enabled'     => 1,
		'url'         => isset( $generated['url'] ) ? (string) $generated['url'] : '',
		'name'        => isset( $generated['name'] ) ? (string) $generated['name'] : get_bloginfo( 'name' ),
		'position'    => 'bottom-right',
		'theme'       => 'light',
		'display'     => 'all',
		'page_ids'    => '',
		'exclude_ids' => '',
		'mobile'      => 1,
	);
}

/**
 * Current options merged with defaults.
 *
 * @return array
 */
function repuvio_badge_options() {
	$saved = get_option( REPUVIO_BADGE_OPTION, array() );

	return wp_parse_args( is_array( $saved ) ? $saved : array(), repuvio_badge_default_options() );
}

/**
 * Parses a comma separated list of post IDs.
 *
 * @param string $value Raw list.
 * @return int[]
 */
function repuvio_badge_parse_ids( $value ) {
	return array_values( array_filter( array_map( 'absint', explode( ',', (string) $value ) ) ) );
}

/**
 * Stores pre-configured values on activation (existing settings are kept).
 *
 * @return void
 */
function repuvio_badge_activate() {
	if ( false === get_option( REPUVIO_BADGE_OPTION ) ) {
		add_option( REPUVIO_BADGE_OPTION, repuvio_badge_default_options() );
	}
}
register_activation_hook( __FILE__, 'repuvio_badge_activate' );

/**
 * Sanitizes the settings form.
 *
 * @param array $input Raw input.
 * @return array
 */
function repuvio_badge_sanitize( $input ) {
	$input    = is_array( $input ) ? $input : array();
	$defaults = repuvio_badge_default_options();
	$url      = isset( $input['url'] ) ? esc_url_raw( trim( (string) $input['url'] ), array( 'http', 'https' ) ) : '';

	if ( '' === $url && ! empty( $input['url'] ) ) {
		add_settings_error( REPUVIO_BADGE_OPTION, 'repuvio_badge_url', __( 'Linkul paginii de evaluare nu este valid (trebuie să înceapă cu https://).', 'repuvio-trust-badge' ) );
	}

	return array(
		'enabled'     => empty( $input['enabled'] ) ? 0 : 1,
		'url'         => $url,
		'name'        => isset( $input['name'] ) ? sanitize_text_field( $input['name'] ) : $defaults['name'],
		'position'    => isset( $input['position'] ) && in_array( $input['position'], array( 'bottom-right', 'bottom-left', 'shortcode' ), true ) ? $input['position'] : 'bottom-right',
		'theme'       => isset( $input['theme'] ) && in_array( $input['theme'], array( 'light', 'dark' ), true ) ? $input['theme'] : 'light',
		'display'     => isset( $input['display'] ) && in_array( $input['display'], array( 'all', 'front_page', 'selected' ), true ) ? $input['display'] : 'all',
		'page_ids'    => implode( ',', repuvio_badge_parse_ids( isset( $input['page_ids'] ) ? $input['page_ids'] : '' ) ),
		'exclude_ids' => implode( ',', repuvio_badge_parse_ids( isset( $input['exclude_ids'] ) ? $input['exclude_ids'] : '' ) ),
		'mobile'      => empty( $input['mobile'] ) ? 0 : 1,
	);
}

/**
 * Registers the settings.
 *
 * @return void
 */
function repuvio_badge_register_settings() {
	register_setting(
		'repuvio_badge',
		REPUVIO_BADGE_OPTION,
		array(
			'type'              => 'array',
			'sanitize_callback' => 'repuvio_badge_sanitize',
			'default'           => repuvio_badge_default_options(),
		)
	);
}
add_action( 'admin_init', 'repuvio_badge_register_settings' );

